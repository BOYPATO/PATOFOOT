function getPosFromRole(role: DetailedRole): Position {
  if (role === 'GOL') return 'GK';
  if (role === 'ZAG' || role === 'LAT') return 'DF';
  if (role === 'VOL' || role === 'MEI') return 'MF';
  return 'FW';
}

function buildAfcGuestClub(params: {
  id: string;
  name: string;
  shortName: string;
  initials: string;
  country: string;
  managerName: string;
  primary: string;
  secondary: string;
  text: string;
  stadiumName: string;
  capacity: number;
  baseOvr: number;
  reputation: number;
  keyPlayers: Array<[string, DetailedRole, number, number, number]>;
}): Club {
  const squad: Player[] = params.keyPlayers.map(([pName, role, ovr, age, num], idx) => {
    const pid = `${params.id}_p_${idx + 1}`;
    return {
      id: pid,
      name: pName,
      nationality: resolvePlayerNationality({ id: pid, name: pName }, params.country),
      position: getPosFromRole(role),
      detailedRole: role,
      overall: ovr,
      age,
      condition: 98,
      morale: 'Excelente',
      wage: Math.round(ovr * 16000),
      marketValue: Math.round(ovr * 1100000),
      contractYears: 3,
      preferredFoot: idx % 3 === 0 ? 'Canhoto' : 'Destro',
      specialSkill: idx < 3 ? 'Destaque Continental' : 'Titular Regular',
      matches: 14,
      goals: role === 'ATA' ? 7 : role === 'MEI' ? 3 : 0,
      assists: role === 'MEI' || role === 'LAT' ? 4 : 1,
      yellowCards: 1,
      redCards: 0,
      isSuspended: false,
      injuryWeeks: 0,
      isStarter: idx < 11,
      isSubstitute: idx >= 11 && idx < 18,
      pitchSlot: idx < 11 ? idx : undefined,
      squadNumber: num,
      ratingAverage: 7.2,
      potential: Math.min(92, ovr + 3),
    };
  });

  return {
    id: params.id,
    name: params.name,
    shortName: params.shortName,
    initials: params.initials,
    state: 'INT',
    division: 'WL',
    reputation: params.reputation,
    country: params.country,
    colors: { primary: params.primary, secondary: params.secondary, text: params.text },
    stadium: { name: params.stadiumName, capacity: params.capacity, ticketPrice: 120, level: 4 },
    finances: {
      balance: params.baseOvr * 3_500_000,
      weeklySponsor: params.baseOvr * 25_000,
      weeklyExpenses: params.baseOvr * 18_000,
      stadiumLevel: 4,
      trainingFacilityLevel: 4,
      medicalFacilityLevel: 4,
      youthAcademyLevel: 4,
      seasonTicketHolders: 28000,
      totalIncomeSeason: params.baseOvr * 1_600_000,
      totalExpensesSeason: params.baseOvr * 1_100_000,
    },
    tactics: {
      formation: '4-3-3',
      mentality: 'Equilibrado',
      marking: 'Normal',
      passing: 'Curto (Posse)',
      captainId: squad[3]?.id,
      penaltyTakerId: squad[9]?.id,
      freekickTakerId: squad[7]?.id,
      cornerTakerId: squad[6]?.id,
    },
    squad,
    isUser: false,
    managerName: params.managerName,
  };
}

function makeStandardRoster(
  prefix: string,
  baseOvr: number,
  starters: Array<[string, DetailedRole, number, number, number]>
): Array<[string, DetailedRole, number, number, number]> {
  const b = Math.max(63, baseOvr - 3);
  const subs: Array<[string, DetailedRole, number, number, number]> = [
    [`${prefix} GK Reserva`, 'GOL', b - 1, 27, 12],
    [`${prefix} Zagueiro`, 'ZAG', b, 25, 14],
    [`${prefix} Lateral`, 'LAT', b - 1, 24, 16],
    [`${prefix} Volante`, 'VOL', b, 26, 18],
    [`${prefix} Armador`, 'MEI', b, 23, 20],
    [`${prefix} Centroavante`, 'ATA', b, 25, 21],
    [`${prefix} Ponta`, 'ATA', b - 1, 22, 19],
  ];
  return [...starters, ...subs];
}

