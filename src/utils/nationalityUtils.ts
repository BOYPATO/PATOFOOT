export function isGeneratedPlayerId(id?: string): boolean {
  if (!id) return false;
  return (
    id.includes('_gen_') ||
    id.includes('_depth_') ||
    id.startsWith('youth_') ||
    id.startsWith('scout_plr_') ||
    id.includes('_sub_') ||
    id.startsWith('regen_')
  );
}

export function normalizeNationality(raw?: string, fallbackCountry: string = 'Brasil'): string {
  if (!raw || !raw.trim()) {
    return normalizeCountryFallback(fallbackCountry);
  }
  const trimmed = raw.trim();
  if (COUNTRY_NATIONALITY_CATALOG[trimmed]) {
    return trimmed;
  }
  const lower = trimmed.toLowerCase();
  if (COUNTRY_SYNONYMS[lower]) {
    return COUNTRY_SYNONYMS[lower];
  }
  const asciiLower = trimmed
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
  if (COUNTRY_SYNONYMS[asciiLower]) {
    return COUNTRY_SYNONYMS[asciiLower];
  }
  // If multi-country region string accidentally leaked (e.g. "Paraguai / Chile"), take first canonical country
  if (trimmed.includes('/')) {
    const firstPart = trimmed.split('/')[0].trim();
    return normalizeNationality(firstPart, fallbackCountry);
  }
  return trimmed;
}

function normalizeCountryFallback(fallbackCountry?: string): string {
  if (!fallbackCountry || !fallbackCountry.trim()) return 'Brasil';
  const trimmed = fallbackCountry.trim();
  if (COUNTRY_NATIONALITY_CATALOG[trimmed]) return trimmed;
  const lower = trimmed.toLowerCase();
  return COUNTRY_SYNONYMS[lower] || 'Brasil';
}

export function resolvePlayerNationality(
  player: { id?: string; name: string; nationality?: string },
  clubCountry?: string
): string {
  // Players directly parsed from official BRASILEIRO SERIE A / B / C .txt carry verified nationality
  if (
    (player.id?.includes('_sa26_') ||
      player.id?.includes('_sb26_') ||
      player.id?.includes('_sc26_') ||
      player.id?.includes('_epl26_')) &&
    player.nationality &&
    player.nationality.trim()
  ) {
    return normalizeNationality(player.nationality, clubCountry || 'Brasil');
  }

  const generated = isGeneratedPlayerId(player.id);

  // For real-life players (or multi-word calibrated real stars), enforce their true FIFA nationality
  if (player.name) {
    const key = normalizePlayerKey(player.name);
    if (key === 'erick' && (player.id?.startsWith('fla_') || player.nationality === 'Chile')) {
      return 'Chile';
    }
    if (
      key === 'emiliano martinez' &&
      (player.id?.startsWith('pal_') || player.nationality === 'Uruguai')
    ) {
      return 'Uruguai';
    }
    const knownRealNat = REAL_PLAYER_NATIONALITIES_BY_NAME[key];
    if (knownRealNat && (!generated || key.includes(' '))) {
      return knownRealNat;
    }
  }

  if (player.nationality && player.nationality.trim()) {
    return normalizeNationality(player.nationality, clubCountry || 'Brasil');
  }

  return normalizeNationality(clubCountry, 'Brasil');
}

